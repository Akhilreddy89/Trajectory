export async function seedCoursesBatch2() {
  try {
    await connectDB();

    console.log(`Seeding ${coursesData2.length} additional courses (batch 2)...`);

    // Avoid duplicate titles if this script is run more than once
    const existingTitles = new Set(
      (await Course.find({}, "title")).map((c) => c.title)
    );
    const newCourses = coursesData2.filter((c) => !existingTitles.has(c.title));

    if (newCourses.length === 0) {
      console.log(" All batch 2 courses already exist. Nothing to insert.");
    } else {
      const inserted = await Course.insertMany(newCourses);
      console.log(`  Successfully seeded ${inserted.length} new courses.`);

      const byCategory = {};
      inserted.forEach((c) => {
        byCategory[c.category] = (byCategory[c.category] || 0) + 1;
      });
      console.log("\nBatch 2 Summary:");
      console.log("   Categories:", byCategory);
      console.log(`   Skipped (already existed): ${coursesData2.length - newCourses.length}`);
    }

    await mongoose.disconnect();
    console.log("\n Disconnected from MongoDB.");
  } catch (err) {
    console.error("  Seeding failed:", err);
    await mongoose.disconnect();
    process.exit(1);
  }
}


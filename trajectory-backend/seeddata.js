// ─── Seed Function ────────────────────────────────────────────────────────────
export async function seedCourses() {
  try {
    await connectDB();

    const existing = await Course.countDocuments();
    if (existing > 0) {
      console.log(`⚠️  Database already has ${existing} courses. Dropping and re-seeding...`);
      await Course.deleteMany({});
    }

    console.log(`🌱  Seeding ${coursesData.length} courses...`);
    const inserted = await Course.insertMany(coursesData);
    console.log(`✅  Successfully seeded ${inserted.length} courses.`);

    // Summary
    const byLevel = {
      beginner: inserted.filter(c => c.level === "beginner").length,
      intermediate: inserted.filter(c => c.level === "intermediate").length,
      advanced: inserted.filter(c => c.level === "advanced").length,
    };
    const byCategory = {};
    inserted.forEach(c => {
      byCategory[c.category] = (byCategory[c.category] || 0) + 1;
    });
    const bySource = {};
    inserted.forEach(c => {
      bySource[c.source] = (bySource[c.source] || 0) + 1;
    });

    console.log("\n📊  Seed Summary:");
    console.log("   Levels:", byLevel);
    console.log("   Categories:", byCategory);
    console.log("   Sources:", bySource);

    await mongoose.disconnect();
    console.log("\n🔌  Disconnected from MongoDB.");
  } catch (err) {
    console.error("❌  Seeding failed:", err);
    await mongoose.disconnect();
    process.exit(1);
  }
}

// ─── Run directly: node db.js ─────────────────────────────────────────────────
seedCourses();